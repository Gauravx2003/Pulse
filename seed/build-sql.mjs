#!/usr/bin/env node
// Base seed generator (task 2.3).
//
// Turns seed/extracted/*.json into SQL seed files run by the backend seed loader (task 1.3):
//   S100__roles_and_rules.sql  base data for every environment: built-in roles and their permission
//                              grants (rbac-visibility), rule defaults (reference section 12) as
//                              rule version 1
//   S110__demo_org.sql         demo organisation: demo accounts (password demo123, bcrypt cost 12
//                              via pgcrypto), people with level, department, joined date and CTC,
//                              effective-dated reporting lines, holidays, sprints and releases
//
// Ingest tables get source = 'seed' and the prototype key as external_id, so the seed connector
// (task 5.4) upserts the same rows. Deterministic; re-run after `node seed/extract.mjs`.
// Usage: node seed/build-sql.mjs [outDir]
import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { REPO_ROOT } from './lib/load-prototype.mjs';

export const EXTRACTED = path.join(REPO_ROOT, 'seed', 'extracted');
export const SEED_SQL_DIR = path.join(REPO_ROOT, 'backend', 'src', 'main', 'resources', 'db', 'seed');
export const BASE_FILE = 'S100__roles_and_rules.sql';
export const DEMO_FILE = 'S110__demo_org.sql';
export const PERFORMANCE_FILE = 'S120__demo_performance.sql';
export const HISTORY_FILE = 'S130__demo_index_history.sql';
export const NOTIFICATIONS_FILE = 'S150__demo_notifications.sql';
/** The quarter the prototype's seeded pillars, 360° ratings and culture signals belong to. */
export const SEEDED_QUARTER = '2026-Q3';
/** The closed quarters before SEEDED_QUARTER, oldest first: the prototype's trend[0..2]. */
export const HISTORY_QUARTERS = ['2025-Q4', '2026-Q1', '2026-Q2'];

export const DEMO_PASSWORD = 'demo123';
/** Department shown by the prototype when a user has none (app.js dept()). */
const DEFAULT_DEPARTMENT = 'Engineering · Platform';
/** Reporting lines for people without a joining date start here. */
const ORG_START = '2022-01-01';

/** Rule key (prototype S.rules) -> Rules & thresholds card (spec platform/rules-thresholds). */
export const RULE_GROUPS = {
  staleDays: 'staleness_capacity', focus: 'staleness_capacity', notStartedPct: 'staleness_capacity',
  nudge: 'staleness_capacity', excludeBots: 'staleness_capacity', dayHours: 'staleness_capacity',
  unplannedAlert: 'staleness_capacity',
  under: 'utilization_bands', healthy: 'utilization_bands', over: 'utilization_bands',
  weights: 'index_weights',
  vw: 'culture_weights', dataShare: 'culture_weights', bonusPerPoint: 'culture_weights', bonusCap: 'culture_weights',
  d5: 'discipline_bands', d4: 'discipline_bands', d3: 'discipline_bands', d2: 'discipline_bands',
  monthCap: 'effort_points', pts: 'effort_points',
  visitCap: 'customer_visits',
  prTitle: 'pr_standard', prMaxLines: 'pr_standard', prMinAppr: 'pr_standard', prCmtMin: 'pr_standard',
  prSla: 'pr_standard', prTarget: 'pr_standard', prItem: 'pr_standard', prDesc: 'pr_standard',
  prThreads: 'pr_standard',
  trWa: 'training', trWm: 'training', trWg: 'training', trWc: 'training', trWp: 'training',
  trPass: 'training', trAssessDays: 'training', trSignDays: 'training',
  att: 'attendance_leave',
  appraisal: 'appraisal_standards',
};
/** Extracted entries that are copies of other defaults, not rules of their own. */
const NOT_RULES = new Set(['valueWeightsDefault', 'prTitlePattern']);

const load = (dir, name) => JSON.parse(readFileSync(path.join(dir, `${name}.json`), 'utf8'));

/** SQL string literal (standard_conforming_strings: only quotes need escaping). */
export const lit = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replaceAll("'", "''")}'`);
const json = (v) => `${lit(JSON.stringify(v))}::jsonb`;
const roleId = (name) => `(SELECT id FROM roles WHERE name = ${lit(name)})`;
const userId = (email) => `(SELECT id FROM users WHERE lower(email) = lower(${lit(email)}))`;
const personId = (key) => `(SELECT id FROM people WHERE source = 'seed' AND external_id = ${lit(key)})`;
const num = (v) => (v === null || v === undefined ? 'NULL' : String(v));

const HEADER = (what) => `-- GENERATED by seed/build-sql.mjs from seed/extracted/*.json - do not edit by hand.
-- ${what}
`;

export function buildBase(dir = EXTRACTED) {
  const roles = load(dir, 'roles');
  const rules = load(dir, 'rule_defaults').filter((r) => !NOT_RULES.has(r.key));
  const unknown = rules.filter((r) => !RULE_GROUPS[r.key]).map((r) => r.key);
  if (unknown.length) throw new Error(`No Rules & thresholds group for: ${unknown.join(', ')} - add them to RULE_GROUPS`);

  const out = [HEADER('Base seed (every environment): built-in roles, permission grants, rule defaults as version 1.')];
  out.push('-- Built-in roles and the default grants of the reference permission matrix');
  for (const r of roles) {
    out.push(`INSERT INTO roles (name, description, built_in) VALUES (${lit(r.name)}, ${lit(r.description)}, ${r.built_in});`);
  }
  for (const r of roles) {
    const values = r.permissions.map((p) => `(${roleId(r.name)}, ${lit(p)})`).join(',\n    ');
    out.push(`INSERT INTO role_permissions (role_id, permission) VALUES\n    ${values};`);
  }

  out.push('\n-- Rule defaults (reference section 12), keys as in the prototype');
  for (const r of rules) {
    out.push(`INSERT INTO rules (key, rule_group, value) VALUES (${lit(r.key)}, ${lit(RULE_GROUPS[r.key])}, ${json(r.value)});`);
  }
  const ruleSet = Object.fromEntries(rules.map((r) => [r.key, r.value]));
  out.push(`INSERT INTO rule_versions (version, rule_set, reason) VALUES (1, ${json(ruleSet)}, 'Defaults');`);
  return out.join('\n') + '\n';
}

export function buildDemo(dir = EXTRACTED) {
  const users = load(dir, 'users');
  const people = load(dir, 'people');
  const joined = Object.fromEntries(load(dir, 'joined_dates').map((x) => [x.person, x.joined_on]));
  const ctc = Object.fromEntries(load(dir, 'ctc').map((x) => [x.person, x.ctc_lakh]));
  const personById = Object.fromEntries(people.map((p) => [p.id, p]));
  const userById = Object.fromEntries(users.map((u) => [u.id, u]));

  const out = [HEADER(`Demo organisation: demo accounts (password ${DEMO_PASSWORD}), people, reporting lines, holidays, sprints, releases.`)];
  out.push('CREATE EXTENSION IF NOT EXISTS pgcrypto WITH SCHEMA public;');

  out.push('\n-- Demo accounts (bcrypt cost 12, hashed by pgcrypto at load time)');
  for (const u of users) {
    const person = u.pid ? personById[u.pid] : null;
    const title = u.title ?? person?.role ?? null;
    const department = u.dept ?? DEFAULT_DEPARTMENT;
    out.push(`INSERT INTO users (email, name, role_id, title, department, status, password_hash) VALUES (${lit(u.email)}, ${lit(u.name)}, ${roleId(u.role)}, ${lit(title)}, ${lit(department)}, ${lit(u.status)}, public.crypt(${lit(DEMO_PASSWORD)}, public.gen_salt('bf', 12)));`);
  }

  out.push('\n-- Performance profiles (Employees)');
  for (const p of people) {
    const user = users.find((u) => u.pid === p.id);
    out.push(`INSERT INTO people (user_id, name, title, department, level, joined_on, ctc, source, external_id) VALUES (${user ? userId(user.email) : 'NULL'}, ${lit(p.name)}, ${lit(p.role)}, ${lit(p.team)}, ${lit(p.level)}, ${lit(joined[p.id])}, ${ctc[p.id] ?? 'NULL'}, 'seed', ${lit(p.id)});`);
  }

  out.push('\n-- Current reporting lines (effective-dated)');
  for (const u of users.filter((x) => x.mgr)) {
    const manager = userById[u.mgr];
    if (!manager) throw new Error(`${u.email}: unknown manager ${u.mgr}`);
    const from = (u.pid && joined[u.pid]) || ORG_START;
    out.push(`INSERT INTO reporting_lines (user_id, manager_id, valid_from) VALUES (${userId(u.email)}, ${userId(manager.email)}, ${lit(from)});`);
  }

  out.push('\n-- Holidays');
  for (const h of load(dir, 'holidays')) {
    out.push(`INSERT INTO holidays (holiday_on, name, source, external_id) VALUES (${lit(h.date)}, ${lit(h.name)}, 'seed', ${lit(h.date)});`);
  }

  out.push('\n-- Sprints');
  for (const s of load(dir, 'sprints')) {
    out.push(`INSERT INTO sprints (key, number, starts_on, work_ends_on, ends_on, source, external_id) VALUES (${lit(s.id)}, ${s.n}, ${lit(s.from)}, ${lit(s.end)}, ${lit(s.to)}, 'seed', ${lit(s.id)});`);
  }

  out.push('\n-- Releases');
  for (const r of load(dir, 'releases')) {
    out.push(`INSERT INTO releases (key, name, starts_on, ends_on, release_date, status, source, external_id) VALUES (${lit(r.id)}, ${lit(r.name)}, ${lit(r.from)}, ${lit(r.to)}, ${lit(r.rel)}, ${lit(r.status)}, 'seed', ${lit(r.id)});`);
  }
  return out.join('\n') + '\n';
}

/**
 * Performance-index inputs for the seeded quarter (tasks 4.3 and 4.4, migration V110): the seeded
 * pillars, the published 360° ratings (combined and per rater group) and the 12 culture signals the
 * prototype generates with its hash function (is_simulated = true).
 */
export function buildPerformance(dir = EXTRACTED) {
  const people = load(dir, 'people');
  const values = load(dir, 'culture_values').sort((a, b) => a.order - b.order).map((v) => v.name);
  const q = SEEDED_QUARTER;

  const out = [HEADER(`Demo performance inputs for ${q}: seeded pillars, 360° culture ratings and the 12 simulated culture signals.`)];

  out.push('\n-- Seeded pillars (Delivery and Quality are read as seeded in v1; OKR and Growth are fallbacks)');
  for (const p of people) {
    const x = p.pillars;
    out.push(`INSERT INTO pillars (person_id, quarter, delivery, quality, okr, growth, source, external_id) VALUES (${personId(p.id)}, ${lit(q)}, ${num(x.delivery)}, ${num(x.quality)}, ${num(x.okr)}, ${num(x.growth)}, 'seed', ${lit(`${p.id}|${q}`)});`);
  }

  out.push('\n-- Published 360° ratings: combined per value, then the rater-group averages');
  for (const p of people) {
    if (p.culture.length !== values.length) throw new Error(`${p.id}: ${p.culture.length} culture ratings, expected ${values.length}`);
    const groups = [['Combined', p.culture], ...Object.entries(p.raters ?? {})];
    for (const [group, ratings] of groups) {
      ratings.forEach((rating, i) => {
        out.push(`INSERT INTO culture_ratings (person_id, quarter, value_name, rater_group, rating, source, external_id) VALUES (${personId(p.id)}, ${lit(q)}, ${lit(values[i])}, ${lit(group)}, ${num(rating)}, 'seed', ${lit(`${p.id}|${q}|${values[i]}|${group}`)});`);
      });
    }
  }

  out.push('\n-- Culture signals with no live source in v1 (generated by the prototype; is_simulated = true)');
  for (const c of load(dir, 'culture_signals')) {
    out.push(`INSERT INTO culture_signals (person_id, quarter, param_key, raw_value, display_value, source_label, is_simulated) VALUES (${personId(c.person)}, ${lit(c.quarter)}, ${lit(c.param_key)}, ${num(c.raw_value)}, ${lit(c.display_value)}, ${lit(c.source_label)}, ${c.is_simulated ? 'true' : 'false'});`);
  }
  return out.join('\n') + '\n';
}

/**
 * The performance index of the closed quarters before the seeded one (task 4.10, migration V120): one
 * `period` snapshot per quarter holding each person's index under `core.index`, taken from the
 * prototype's `trend` (its first three values; the fourth is the live quarter). CalcService serves
 * these quarters from the snapshot; they feed the appraisal performance part and the index trend.
 */
export function buildHistory(dir = EXTRACTED) {
  const people = load(dir, 'people');
  const out = [HEADER(`Demo index history: closed quarters ${HISTORY_QUARTERS.join(', ')} as period snapshots (rule version 1).`)];
  HISTORY_QUARTERS.forEach((q, i) => {
    const rows = people.map((p) => {
      if (!Array.isArray(p.trend) || p.trend.length < HISTORY_QUARTERS.length + 1) throw new Error(`${p.id}: trend needs ${HISTORY_QUARTERS.length + 1} values`);
      return `(${lit(p.id)}, ${num(p.trend[i])})`;
    });
    const inputs = { source: 'seed', from: 'prototype trend', quarter: q, formulas: ['core.index'] };
    out.push(`\n-- ${q}`);
    out.push(`INSERT INTO calc_snapshots (kind, subject_key, rule_version, inputs, result, reason)
SELECT 'period', ${lit(`q:${q}`)}, 1, ${json(inputs)}, jsonb_build_object('core.index', jsonb_object_agg(p.id::text, v.idx)), 'Seeded history'
FROM (VALUES ${rows.join(', ')}) AS v(person_key, idx)
JOIN people p ON p.source = 'seed' AND p.external_id = v.person_key;`);
  });
  return out.join('\n') + '\n';
}

/** Prototype notification kind -> the screen its item opens (spec platform/notifications "In-app notifications"). */
export const NOTIFICATION_LINKS = { seed: '/reviews?tab=360', reminder: '/reviews?tab=360', request: '/reviews?tab=360', training: '/training', visit: '/visits' };

/**
 * S150: the bell's demo notifications, the prototype's `NOTIFS` after start-up (360° requests of the
 * active cycle, training and customer-visit reminders). Each row goes to the account of its `uid`, at
 * 09:00 Asia/Kolkata on its date plus its sequence number in minutes so the prototype's order holds.
 */
export function buildNotifications(dir = EXTRACTED) {
  const users = new Map(load(dir, 'users').map((u) => [u.id, u.email]));
  const rows = load(dir, 'notifications').map((n) => {
    const email = users.get(n.uid);
    if (!email) throw new Error(`notification ${n.id}: unknown user ${n.uid}`);
    const link = NOTIFICATION_LINKS[n.kind];
    if (!link) throw new Error(`notification ${n.id}: no link for kind ${n.kind}`);
    const seq = Number(/^n(\d+)/.exec(n.id)?.[1] ?? 0);
    const kind = n.kind === 'seed' ? 'review360.assigned' : n.kind === 'visit' ? 'visit.reminder' : 'training.reminder';
    const at = `timestamptz ${lit(`${n.at} 09:00:00+05:30`)} + interval ${lit(`${seq} minutes`)}`;
    const readAt = n.read ? at : 'NULL';
    return `INSERT INTO notifications (user_id, kind, text, link, read_at, created_at) VALUES (${userId(email)}, ${lit(kind)}, ${lit(n.text)}, ${lit(link)}, ${readAt}, ${at});`;
  });
  return [HEADER('Demo notifications: the prototype bell after start-up (360° requests, training and visit reminders).'), ...rows].join('\n') + '\n';
}

export function build(outDir = SEED_SQL_DIR, dir = EXTRACTED) {
  mkdirSync(outDir, { recursive: true });
  writeFileSync(path.join(outDir, BASE_FILE), buildBase(dir));
  writeFileSync(path.join(outDir, DEMO_FILE), buildDemo(dir));
  writeFileSync(path.join(outDir, PERFORMANCE_FILE), buildPerformance(dir));
  writeFileSync(path.join(outDir, HISTORY_FILE), buildHistory(dir));
  writeFileSync(path.join(outDir, NOTIFICATIONS_FILE), buildNotifications(dir));
  return [BASE_FILE, DEMO_FILE, PERFORMANCE_FILE, HISTORY_FILE, NOTIFICATIONS_FILE];
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const outDir = process.argv[2] ? path.resolve(process.argv[2]) : SEED_SQL_DIR;
  for (const f of build(outDir)) console.log(`wrote ${path.relative(process.cwd(), path.join(outDir, f))}`);
}
